function Get-DotEnvValue([string]$Name) {
    $line = Get-Content -LiteralPath ".env" |
        Where-Object { $_ -match ("^" + [regex]::Escape($Name) + "=") } |
        Select-Object -Last 1

    if ($null -eq $line) { return "" }
    return ($line -split "=", 2)[1]
}

