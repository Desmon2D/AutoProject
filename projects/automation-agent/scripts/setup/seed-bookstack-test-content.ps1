## Безопасность и эксплуатация

Специалист по безопасности проверяет классификацию данных, права доступа, аудит и сроки хранения. Эксплуатация подтверждает мониторинг, резервное восстановление, лимиты ресурсов и порядок реакции на инциденты. Их согласование обязательно, если сценарий работает с персональными данными, финансовыми операциями или критичным процессом.

