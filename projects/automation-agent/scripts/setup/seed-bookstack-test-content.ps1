## Инициатор

Инициатор формулирует бизнес-проблему, предоставляет известные ограничения и отвечает на вопросы о желаемом результате. Он может видеть собственные запуски и скачивать доступные ему артефакты. Инициатор не утверждает технические решения, если одновременно не является владельцем соответствующего продукта.

## Аналитик

Аналитик определяет границы исследования, оценивает качество источников, редактирует формулировки требований и ведёт список открытых вопросов. Он отвечает за трассировку фактов, но не за доступность внешних систем. Аналитик обязан помечать предположения и не может выдавать автоматически сформированный черновик за согласованный документ.

## Владелец процесса

