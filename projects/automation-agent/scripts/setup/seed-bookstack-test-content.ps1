## Подготовка черновика

Черновик начинается с краткого резюме задачи и описания границ. Затем аналитик моделирует текущий и целевой процессы, выделяет роли, бизнес-правила и данные. Требования формулируются отдельно от решений. Например, «система должна уведомить владельца не позднее пяти минут» является требованием, а «использовать конкретный брокер сообщений» — вариантом реализации, если технология не закреплена архитектурным ограничением.

Каждое функциональное требование получает идентификатор и приоритет. Для приоритета используется шкала Must, Should, Could, Won't for now. Must означает, что без требования целевой процесс не достигает цели или нарушает обязательное правило. Приоритет не определяется только громкостью пожелания заказчика: он должен быть обоснован влиянием на процесс, риском либо зависимостью.

